"""Распознавание колонок: имя заголовка это подсказка, а не приговор."""

from app.ingest.tables import detect_columns, parse_article_table, parse_line

ROWS = [
    ["Как зарегистрироваться на портале?", "Нужна усиленная квалифицированная ЭП.", "1"],
    ["Как подписать контракт с ЭП?", "Откройте карточку контракта и нажмите «Подписать».", "2"],
    ["Почему не приходит УПД?", "Проверьте статус в разделе «Исполнение контракта».", "2"],
]


def test_named_columns_win_when_they_do_not_collide():
    assert detect_columns(["Вопрос", "Ответ", "Линия"], ROWS) == (0, 1)


def test_text_obrashcheniya_is_a_question_not_an_answer():
    """Реальный случай из выгрузки поддержки.

    «Текст обращения» — это вопрос, но слово «текст» стоит в синонимах ответа и
    срабатывает первым. Пока обе колонки схлопывались в одну, лист уезжал в
    «непонятно» и данные терялись целиком, молча.
    """
    assert detect_columns(["Текст обращения", "Решение", "Линия"], ROWS) == (0, 1)


def test_columns_without_any_known_name_are_read_by_content():
    headers = ["Столбец A", "Столбец B"]
    rows = [[row[0], row[1]] for row in ROWS]
    assert detect_columns(headers, rows) == (0, 1)


def test_answer_is_the_longest_text_column():
    headers = ["Тема", "Код", "Подробности"]
    rows = [
        ["Как войти?", "42", "Через электронную подпись в личном кабинете."],
        ["Как выйти?", "43", "Кнопка «Выход» в правом верхнем углу страницы."],
        ["Где УПД?", "44", "В разделе «Исполнение контракта» карточки."],
    ]
    question_at, answer_at = detect_columns(headers, rows)
    assert (question_at, answer_at) == (0, 2)


def test_markdown_table_with_unusual_headers_is_parsed():
    markdown = (
        "| Текст обращения | Решение |\n|---|---|\n"
        "| Как зарегистрироваться на портале? | Нужна электронная подпись и заявка. |\n"
        "| Как подписать контракт? | Откройте карточку контракта и нажмите «Подписать». |\n"
        "| Почему не приходит УПД? | Проверьте статус в разделе «Исполнение». |\n"
        "| Как сменить реквизиты? | В профиле организации, раздел «Банковские счета». |\n"
        "| Куда жаловаться? | В ФАС через форму на портале поставщиков. |\n"
    )
    rows = parse_article_table(markdown)
    assert rows is not None
    assert len(rows) == 5
    assert rows[0]["question"] == "Как зарегистрироваться на портале?"
    assert rows[0]["answer"].startswith("Нужна электронная подпись")


def test_line_column_is_read_from_the_export():
    """Линия из выгрузки — первоисточник, точнее классификатора.

    Кейс хакатона отдельным пунктом требует маршрутизации по линиям поддержки.
    Пока колонку «Линия» игнорировали, номер угадывал классификатор — при том,
    что правильный ответ был написан в соседней ячейке.
    """
    markdown = (
        "| Вопрос | Ответ | Линия |\n|---|---|---|\n"
        "| Как зарегистрироваться на портале? | Нужна электронная подпись. | 1 |\n"
        "| Как подписать контракт? | Откройте карточку контракта. | Л2 |\n"
        "| Почему не приходит УПД? | Проверьте статус исполнения. | 2 |\n"
        "| Как сменить реквизиты? | В профиле организации. | вторая линия |\n"
        "| Куда жаловаться? | В ФАС через форму. | 3 |\n"
        "| Как выгрузить реестр? | Кнопка «Экспорт». |  |\n"
    )
    rows = parse_article_table(markdown)
    assert [row.get("line") for row in rows] == [1, 2, 2, 2, 3, None]


def test_unreadable_line_leaves_the_decision_to_the_classifier():
    assert parse_line("") is None
    assert parse_line("неизвестно") is None
    assert parse_line("42") is None  # линий столько не бывает
    assert parse_line("Л3") == 3
