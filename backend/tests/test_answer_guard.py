# --- grounding ---


def test_invented_term_is_unconfirmed():
    """Главный случай стенда: срока в статье нет, а модель его назвала."""
    source = "По вопросам блокировки личного кабинета обратитесь в СКК через форму обратной связи."
    assert grounding("Блокировка снимется автоматически в течение 10 рабочих дней.", [source]) == [
        "10 рабочих дней"
    ]


def test_numbers_from_source_are_confirmed():
    assert grounding("Жалобу рассмотрят в течение 10 рабочих дней.", [ARTICLE]) == []
    # пропись в статье и цифра в ответе — одно и то же число
    assert grounding("Срок — 10 рабочих дней.", ["в течение десяти рабочих дней"]) == []
    # и наоборот: пропись в скобках после цифры не мешает найти единицу
    assert grounding("Жалобу рассмотрят в течение десяти рабочих дней.", [ARTICLE]) == []


def test_number_with_another_unit_is_unconfirmed():
    """«10 минут» в статье не подтверждает «10 рабочих дней» в ответе."""
    assert grounding("Ответ придёт через 10 рабочих дней.", ["Ответ придёт через 10 минут."]) == [
        "10 рабочих дней"
    ]
    assert grounding("Жалобу рассмотрят в течение 10 календарных дней.", [ARTICLE]) == ["10 календарных дней"]


def test_contacts_dates_and_links_are_checked():
    good = "Звоните 8 495 870 12 34, пишите на help@mos.ru, приём до 31.12.25 с 09:00 до 18:00."
    assert grounding(good, [ARTICLE]) == []
    bad = "Звоните +7 495 111-22-33 или пишите на support@mos.ru до 01.02.2026, сайт example.com."
    assert grounding(bad, [ARTICLE]) == ["support@mos.ru", "example.com", "+7 495 111-22-33", "01.02.2026"]


def test_quoted_names_must_exist_in_source():
    """Название кнопки — ровно как в статье; падеж — не выдумка, чужая кнопка — выдумка."""
    assert grounding("Нажмите «Подать жалобу» в разделе «Личном кабинете».", [ARTICLE]) == []
    assert grounding('Нажмите "Снять блокировку".', [ARTICLE]) == ['"Снять блокировку"']


def test_list_numbering_and_trivial_counts_are_not_facts():
    """Номера пунктов модель расставляет сама, пересобирая инструкцию в список."""
    answer = "Есть 2 способа:\n1. Откройте раздел.\n2. Нажмите кнопку.\n**Шаг 5.** Готово."
    assert grounding(answer, ["Откройте раздел и нажмите кнопку."]) == []


def test_normalization_of_spaces_case_and_yo():
    source = "Лимит — 1 000 000 рублей, заявку подаёт «Заказчик»."
    assert grounding("Лимит 1 000 000 руб., заявку подает «заказчик».", [source]) == []
    assert grounding("Скидка 15%.", ["скидка 15 процентов"]) == []
    assert grounding("Скидка 15%.", ["скидка 20 процентов"]) == ["15%"]


def test_user_words_confirm_their_identifiers():
    """Номер контракта, почта и телефон из реплик человека в ответе — не выдумка."""
    article = "Расторгнуть контракт можно в разделе «Контракты»."
    answer = "Контракт 0373200041524000123 можно расторгнуть в разделе «Контракты»."
    assert grounding(answer, [article]) == ["0373200041524000123"]
    assert grounding(answer, [article], ["контракт 0373200041524000123"]) == []
    contacts = "Ответ придёт на ivanov@firma.ru, перезвоним на 8 (916) 123-45-67."
    assert grounding(contacts, [article], ["почта ivanov@firma.ru, тел. +7 916 123 45 67"]) == []


def test_leading_question_does_not_confirm_a_term():
    """Стенд: на «снимут через 3 рабочих дня?» модель поддакнула сроку из вопроса.

    Срок, сумму, дату и название из реплики человека подтверждает только статья:
    иначе выдумка уходит к нему как найденная в базе знаний.
    """
    article = "По вопросам блокировки личного кабинета обратитесь в СКК через форму обратной связи."
    question = "Блокировку ЛК снимут автоматически через 3 рабочих дня?"
    answer = "Да, блокировка снимется автоматически через 3 рабочих дня."
    assert grounding(answer, [article], [question]) == ["3 рабочих дня"]
    assert grounding(
        "Да, лимит 1 000 000 рублей до 31.12.2025, кнопка «Снять блокировку».",
        [article],
        ["лимит 1 000 000 рублей до 31.12.2025? есть кнопка «Снять блокировку»?"],
    ) == ["«Снять блокировку»", "31.12.2025", "1 000 000 рублей"]


# Фразы — из регламента и базы знаний портала: так в них пишут годы, даты,
# сокращения и числа прописью, а модель пересказывает это по-своему.
@pytest.mark.parametrize(
    "answer, source",
    [
        (
            "Положение утверждено в 2018 году.",
            "постановлением Правительства Москвы от 24 октября 2018 г. N 1292-ПП",
        ),
        (
            "Постановление от 24.10.2018.",
            "постановлением Правительства Москвы от 24 октября 2018 г. N 1292-ПП",
        ),
        ("Порядок утверждён 30 июня 2021 года.", "от 30.06.2021 N 1078 «О порядке ведения реестра»"),
        ("Приказ действует с 2024 года.", "приказ от 14 февраля 2024 г. № 70-01-17/24"),
        (
            "Если размер превышает 25% балансовой стоимости активов.",
            "размер которых превышает двадцать пять процентов балансовой стоимости активов",
        ),
        (
            "Жалобу рассматривают 10 рабочих дней.",
            "Арбитражная комиссия АИС «Портал поставщиков» рассматривает жалобу "
            "в течение десяти рабочих дней",
        ),
        (
            "1.3. Текст Регламента публикуется.\n1.4. Документы формируются в АИС.",
            "1.3. Текст настоящего Регламента, в том числе с учетом внесенных изменений",
        ),
        (
            "Ответ в течение 24 часов, срок — 5 рабочих дней или 2 недели.",
            "Ответ — 24 ч. Срок — 5 раб. дней или 2 нед.",
        ),
    ],
)
def test_rewording_of_real_facts_is_confirmed(answer, source):
    assert grounding(answer, [source]) == []


def test_rewording_does_not_loosen_the_check():
    """Другой год, день или срок по-прежнему выдумка — пусть и записанная иначе."""
    source = "от 24 октября 2018 г. N 1292-ПП; жалобу рассматривают в течение десяти рабочих дней"
    assert grounding("Принято 24 октября 2019 года.", [source]) == ["24 октября 2019"]
    assert grounding("Принято 25.10.2018.", [source]) == ["25.10.2018"]
    assert grounding("Жалобу рассмотрят за 15 рабочих дней.", [source]) == ["15 рабочих дней"]
    # «двадцать пять» — это 25, а не 20 и 5
    assert grounding("Срок — 5 дней.", ["в течение двадцати пяти дней"]) == ["5 дней"]
    # многоуровневый номер пункта — только перед заглавной; «1.5 часа» — срок
    assert grounding("1.5 часа на подписание.", ["2 часа на подписание."]) == ["1.5 часа"]


