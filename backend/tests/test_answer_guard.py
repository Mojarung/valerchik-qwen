def test_overlap_shows_which_article_was_retold():
    supplier = "Поставщик подаёт предложение в карточке КС на странице «Котировочные сессии»."
    customer = "Заказчик создаёт КС в разделе «Закупки»."
    answer = "Поставщик подаёт предложение в карточке котировочной сессии в течение 2 часов."
    assert overlap(answer, supplier) > overlap(answer, customer)
    assert overlap("", supplier) == 0.0
