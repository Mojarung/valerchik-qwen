"""Строки оглавления PDF — служебные: «Раздел ........ 7» не ответ ни на что.

Разбор инструкций портала нарезал из оглавления десятки кусков, и на замере по
реальным обращениям один из них вышел первым на жалобу про контракт: вопрос
«Условные обозначения… 7», ответ «163 / 11.3 Исполнения…».
"""

from app.ingest.boilerplate import strip_boilerplate

TOC = """Содержание
1. Общие положения ........................................ 5
2.2. Уровень подготовки пользователя ...................... 7
Подключение электронной подписи.................................................
11.3 Исполнения ............................................................. 163

Подключение электронной подписи
Для подписания документов вставьте носитель и выберите сертификат.
"""


def test_toc_lines_are_removed():
    cleaned = strip_boilerplate(TOC)

    assert "......" not in cleaned
    assert "Уровень подготовки пользователя" not in cleaned
    # Содержательный текст раздела остаётся на месте
    assert "Для подписания документов вставьте носитель и выберите сертификат." in cleaned


def test_ordinary_ellipsis_is_kept():
    text = "Нажмите «Далее»... и дождитесь загрузки страницы."
    assert strip_boilerplate(text).strip() == text
