"""Помощники для текста, который читает человек: основа слова, частые значимые
слова и согласование с числом.

Основу считает пакет snowballstemmer. Пары ниже — контракт с ним: формы, которые
отчёт обязан склеить («линии»/«линию», «решён»/«решен»), и слова, которые обрезать
нельзя («ответ», «аукцион»). Обновление пакета, которое их поменяет, будет видно здесь.
"""

import pytest

from app.services.wordforms import plural, stem, top_words


@pytest.mark.parametrize(
    ("word", "expected"),
    [
        # существительные: формы одного слова — одна основа
        ("оператора", "оператор"),
        ("операторов", "оператор"),
        ("линии", "лин"),
        ("линию", "лин"),
        ("авторизация", "авторизац"),
        # окончание ищется только после первой гласной, а глагольное «ет», «н» —
        # только после «а»/«я»: иначе «ответ» терял бы «ет», а «аукцион» — «н»
        ("ответ", "ответ"),
        ("ответа", "ответ"),
        ("был", "был"),
        ("аукцион", "аукцион"),
        ("ждал", "ждал"),
        ("ждали", "ждал"),
        # глаголы и возвратные
        ("работает", "работа"),
        ("молчит", "молч"),
        ("адресована", "адресова"),
        ("дождался", "дожда"),
        ("блокируется", "блокир"),
        ("бойся", "бо"),
        # прилагательные и причастия
        ("непонятная", "непонятн"),
        ("бегавшая", "бега"),
        ("временный", "времен"),
        ("внутренняя", "внутрен"),
        # деепричастия; «ов» у существительного — не деепричастное «в»
        ("получив", "получ"),
        ("сделавши", "сдела"),
        ("документов", "документ"),
        # «и» после окончания, мягкий знак, удвоенная «н»
        ("информацию", "информац"),
        ("историю", "истор"),
        ("подписью", "подпис"),
        ("статьи", "стат"),
        ("длинный", "длин"),
        # словообразовательное «ость» — только в R2; превосходная степень
        ("возможность", "возможн"),
        ("радость", "радост"),
        ("важнейшими", "важн"),
        # «ё» пишут не всегда — основа от этого не зависит
        ("решён", "реш"),
        ("решен", "реш"),
    ],
)
def test_stem_matches_snowball(word, expected):
    assert stem(word) == expected


def test_top_words_filter_service_words_by_whole_word_not_by_stem():
    # «тем» — служебное слово, а «тема» с той же основой — нет
    words = top_words(["Тем временем тема так и не раскрыта"], 5)
    assert "тема" in words
    assert "тем" not in words


def test_top_words_keep_yo_and_drop_short_tokens():
    assert top_words(["Вопрос не решён, ошибка 500 уже 5 раз"], 5) == ["вопрос", "решён", "ошибка", "500"]


def test_top_words_cut_to_limit_in_order_of_first_appearance_on_ties():
    assert top_words(["альфа бета гамма дельта эпсилон"], 3) == ["альфа", "бета", "гамма"]


def test_top_words_put_frequent_words_first():
    assert top_words(["альфа бета", "бета гамма", "бета гамма"], 2) == ["бета", "гамма"]


@pytest.mark.parametrize(
    ("count", "form"),
    [
        (1, "обращение"),
        (21, "обращение"),
        (101, "обращение"),
        (-1, "обращение"),
        (2, "обращения"),
        (4, "обращения"),
        (22, "обращения"),
        (0, "обращений"),
        (5, "обращений"),
        (11, "обращений"),
        (12, "обращений"),
        (14, "обращений"),
        (111, "обращений"),
    ],
)
def test_plural(count, form):
    assert plural(count, ("обращение", "обращения", "обращений")) == form
