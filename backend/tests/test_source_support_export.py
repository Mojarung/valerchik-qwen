def _book(sheets: dict[str, list[list[str]]]) -> bytes:
    """Книга в памяти: первая строка каждого листа — заголовки."""
    book = openpyxl.Workbook()
    book.remove(book.active)
    for title, rows in sheets.items():
        sheet = book.create_sheet(title)
        for row in rows:
            sheet.append(row)
    buffer = io.BytesIO()
    book.save(buffer)
    return buffer.getvalue()


def _row(
    text: str,
    answer: str,
    *,
    topic: str = "Работа с СТЕ",
    subtopic: str = "Ошибка в карточке СТЕ",
    impact: str = RFI,
) -> list[str]:
    description = f"Подтема запроса: {subtopic}/{text}" if subtopic else text
    return [impact, "Заявитель", topic, "Завершено", description, answer]


def _export(rows: list[list[str]]) -> bytes:
    return _book({"Sheet1": [HEADERS, *rows]})


async def _parse(data: bytes, ctx: IngestContext | None = None):
    source = SupportExportSource()
    blob = FileBlob(name="Выгрузка СТП.xlsx", data=data)
    return [record async for record in source.parse(blob, ctx or IngestContext())]


