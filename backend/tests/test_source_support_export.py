def test_classify_answer_keeps_rules_for_everyone():
    # Номер закона — не номер заявки: такие ответы самые общие в выгрузке
    law = (
        "В соответствии с частью 2.3 статьи 15 Федерального закона от 08.03.2022 № 46-ФЗ электронные "
        "документы о приемке формируются в ЕИС без использования Портала поставщиков."
    )
    assert classify_answer(law) == (kbkind.ANSWER, law)
    # Просьба «на случай» — совет всем, а не вопрос одному
    retry = (
        "Рекомендуется повторить операцию прикрепления МЧД. "
        "В случае возобновления ошибки просьба прислать полноэкранный скриншот."
    )
    assert classify_answer(retry) == (kbkind.ANSWER, retry)
    # Частность в первой фразе отрезается, инструкция после неё — ответ
    mchd = (
        "В МЧД с № 83dfc76c-d5e1-4165-922b-31def0a5f73c нет полномочий для работы на Портале поставщиков. "
        "Необходимо сформировать МЧД на сайте ФНС в разделе «Создать доверенность» и выбрать полномочия "
        "из классификатора с префиксом DIT_PP."
    )
    assert classify_answer(mchd) == (kbkind.ANSWER, mchd.split(". ", 1)[1])
    # Отправка приглашения — шаг, который заявитель делает и сам: порядок после неё общий
    sent = (
        "Заказчику отправлено приглашение на установку связи. Заказчику требуется принять приглашение, "
        "далее поставщику необходимо повторно подписать и отправить УПД."
    )
    assert classify_answer(sent) == (kbkind.ANSWER, sent.split(". ", 1)[1])


def test_classify_answer_catches_reports_that_look_like_instructions():
    # «Ошибка исправлена» и просьба на случай — ни одной инструкции
    fixed = (
        "Ошибка исправлена. В случае возобновления ошибки просьба прислать полноэкранный скриншот "
        "с открытой вкладкой Console."
    )
    assert classify_answer(fixed)[0] == kbkind.OPERATOR_CASE
    # Временный сбой: совет в таком ответе — про этот сбой, после починки он неправда
    incident = (
        "По данной проблеме заведена массовая задача 33550005. Ведутся работы по восстановлению. "
        "Раз в час рекомендуем повторять отправку УПД на подписание."
    )
    assert classify_answer(incident)[0] == kbkind.OPERATOR_CASE
    # Что после действия за заявителя — только тому, кому вернули победу
    returned = (
        "Победа по котировочной сессии возвращена. Переподпишите оферту для формирования нового проекта "
        "контракта и свяжитесь с заказчиком, чтобы он очистил данные в электронном магазине."
    )
    assert classify_answer(returned)[0] == kbkind.OPERATOR_CASE
    # Без номеров из середины совет «обратитесь к заказчику» — ни о чём
    kpp = (
        "Проблема на стороне системы заказчика ЕАИСТ. У вас указан КПП 771601001, а в карточке контракта "
        "указан КПП 772401001. Обратитесь к заказчику для исправления КПП в контракте, после этого "
        "повторите отправку."
    )
    assert classify_answer(kpp)[0] == kbkind.OPERATOR_CASE
    # Остаток ссылается на отрезанную фразу («Его…») — без неё не читается
    draft = (
        "На момент проверки черновик исполнения есть в ГИС ЕИС. Его необходимо удалить в личном кабинете "
        "ГИС ЕИС, либо использовать на Портале поставщиков другой номер документа."
    )
    assert classify_answer(draft)[0] == kbkind.OPERATOR_CASE
    # Просьба «на случай» без единой инструкции — встречный вопрос
    token = "В случае если токен указан корректно, в новом обращении предоставьте скриншот токена."
    assert classify_answer(token)[0] == kbkind.OPERATOR_CASE


