@pytest.mark.asyncio
async def test_sniff_takes_the_export_and_leaves_plain_qa_to_spreadsheet():
    source = SupportExportSource()
    export = _export([_row("Как исправить ошибку в СТЕ?", ANSWER_STE)])
    qa = _book({"Вопросы": [["Вопрос", "Ответ"], ["Как войти?", "Через ЭП."]]})

    assert await source.sniff(FileBlob(name="stp.xlsx", data=export)) == CONFIDENCE
    assert await source.sniff(FileBlob(name="qa.xlsx", data=qa)) == 0.0
    markdown = "| Тема | Описание | Решение |".encode()
    assert await source.sniff(FileBlob(name="stp.md", data=markdown)) == 0.0
    # Битую книгу пусть пробует кто-то другой: реестр спрашивает sniff у всех подряд
    assert await source.sniff(FileBlob(name="stp.xlsx", data=b"not a book")) == 0.0

    # В реестре выгрузка уходит нам, а обычная книга — по-прежнему spreadsheet:
    # его 0.90 против наших 0.97 на выгрузке и 0.0 на всём остальном.
    picked = await pick_source(FileBlob(name="stp.xlsx", data=export))
    assert picked is not None and picked.name == "support_export"
    picked = await pick_source(FileBlob(name="qa.xlsx", data=qa))
    assert picked is not None and picked.name == "spreadsheet"


@pytest.mark.asyncio
async def test_same_answer_in_different_spelling_becomes_one_article():
    rows = [
        _row("Нашёл ошибку в карточке СТЕ, как исправить?", ANSWER_STE_ESCAPED),
        _row("В зарегистрированной СТЕ неверно указан производитель, что делать", ANSWER_STE_ESCAPED),
        _row("В карточке СТЕ ошибка в единице измерения, исправьте пожалуйста", ANSWER_STE_SLOPPY),
        # Перефраз вопроса и его точный повтор — не новые формулировки
        _row("Нашёл ошибку в карточке СТЕ, как её исправить?", ANSWER_STE_ESCAPED),
        _row("Нашёл ошибку в карточке СТЕ, как исправить?", ANSWER_STE_ESCAPED),
    ]
    records = await _parse(_export(rows))

    assert len(records) == 1
    article = records[0]
    # Ответ — самый частый вариант написания, без экранирования тикет-системы
    assert article.answer == ANSWER_STE
    assert "\\" not in article.answer
    # Вопрос — реальное обращение со знаком вопроса, а не «Подтема запроса: …»
    assert article.question == "Нашёл ошибку в карточке СТЕ, как исправить?"
    # Подтема и тема — в ключевые слова, за ними непохожие формулировки
    assert article.keywords == [
        "Ошибка в карточке СТЕ",
        "Работа с СТЕ",
        "В зарегистрированной СТЕ неверно указан производитель, что делать",
        "В карточке СТЕ ошибка в единице измерения, исправьте пожалуйста",
    ]
    assert article.category == "Работа с СТЕ"
    assert article.line is None
    # Ответ писал оператор: его можно отдавать дословно, и это инструкция всем
    assert article.origin.authored is True
    assert article.origin.kind == kbkind.ANSWER
    assert article.origin.as_dict()["kind"] == kbkind.ANSWER
    assert article.origin.source_name == "support_export"
    assert article.origin.locator == "лист «Sheet1», строки 1…5 (5 обращений)"


