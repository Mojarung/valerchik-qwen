def test_near_duplicates():
    # Один ответ в редакции разных операторов
    tail = "приглашение на установку связи, после принятия приглашения повторите подписание УПД."
    assert near_duplicates(f"Заказчику направлено {tail}", f"Заказчику отправлено {tail}")
    # Частица «не» переворачивает смысл, сколько бы слов ни совпало
    assert not near_duplicates(
        "На момент проверки сведений организация не заблокирована на Портале поставщиков.",
        "На момент проверки сведений организация заблокирована на Портале поставщиков.",
    )
    # Общая длинная ссылка на инструкцию не делает разные пункты одним ответом
    link = "https://zakupki.mos.ru/cms/media/docs/%D0%98%D0%BD%D1%81%D1%82%D1%80%D1%83%D0%BA%D1%86%D0%B8%D1%8F.pdf"
    assert not near_duplicates(
        f"Рекомендуем ознакомиться с пунктом 5.2.2 «Добавить токен» инструкции {link}",
        f"Рекомендуем ознакомиться с пунктом 8.15 «Сведения о маркировке» инструкции {link}",
    )


def test_tidy_question():
    # Приветствие, благодарность и лишние знаки вопроса — не вопрос
    assert (
        tidy_question("Добрый день! Уважаемые коллеги, как подписать УПД???? Спасибо") == "Как подписать УПД?"
    )
