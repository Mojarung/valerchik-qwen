"""Одна реплика пользователя на пути через конвейер ответа.

Шаги конвейера — уточнение, дословная цитата, ответ агента — спрашивают об одном
и том же: что сказали, в каком диалоге, от чьего имени, что нашёл пробный поиск
и когда всё началось. Раньше это ездило пятью-шестью аргументами в каждый шаг.
"""

from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from app.services.retrieval import RetrievedDoc


@dataclass(frozen=True)
class FollowUp:
    """Прошлый вопрос, который продолжает реплика («а для заказчика?»)."""

    question: str
    # Статьи, которыми бот на него ответил: повторять их дословно незачем.
    sources: tuple[str, ...] = ()


@dataclass
class Turn:
    session_id: str
    # Текст после починки раскладки; ответ на «вы поставщик или заказчик?»
    # заменяет его прежним вопросом — искать надо его, а не «я заказчик».
    # Продолжение («а сроки?») — склейкой с прошлым вопросом (chat/followup.py).
    text: str
    # perf_counter() в момент приёма — от него считается время ответа.
    started: float
    # Статус диалога на момент приёма: у оператора агент молчит.
    status: str = "active"
    # Роль собеседника: supplier, customer или пусто.
    role: str = ""
    # Раздел портала текстом — подсказка поиску.
    page_text: str = ""
    # id сохранённой реплики — на неё ссылается черновик копилота.
    message_id: str = ""
    # Пробный поиск по базе знаний: решает и про уточнение, и про внешние инструменты.
    probe: list[RetrievedDoc] | None = None
    # Нужны ли внешние инструменты (MCP) для этого вопроса.
    need_mcp: bool = False
    # Флаги для meta ответа: подозрение на подмену инструкций, сбой внешнего инструмента.
    flags: dict[str, Any] = field(default_factory=dict)
    # Слова самого человека в этом ходе: text бывает подменён прошлым вопросом.
    said: str = ""
    # Какой прошлый вопрос продолжает реплика; None — вопрос самостоятельный.
    follow_up: FollowUp | None = None
