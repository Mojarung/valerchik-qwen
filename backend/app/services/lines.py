# Приставки, которые тикет-система или оператор дописывали к теме:
# «INTEGRTP-57973 Электронное исполнение (малый объем)», «ОШ Личный кабинет
# пользователя», «Консультация - Контракты (44-ФЗ)».
_TOPIC_PREFIX = re.compile(
    r"^(?:integrtp\s*-?\s*\d+\)?\s*|ош\s+|консультация\s*-\s*|предложение по доработке\s*-\s*)+",
    re.IGNORECASE,
)


def normalize_topic(raw: str, subtopic: str = "", learned: Mapping[str, str] | None = None) -> str | None:
    """Тема выгрузки → тема справочника или None, если её не восстановить.

    Порядок — от надёжного к догадке: сама тема (с точностью до точки на конце и
    приставки номера задачи), затем подтема (у подтемы справочника хозяин один),
    затем самодельное название темы. Подтема идёт раньше синонима: «Контракты
    (44-ФЗ)» с подтемой «Отправка УПД» — это электронное исполнение, а не контракт.
    `learned` — соответствия подтем, выведенные из самой выгрузки (варианты
    написания вроде «Исполнение контракта (не электронное исполнение)»).
    """
    key = topic_key(_TOPIC_PREFIX.sub("", raw.strip()))
    if key in _TOPIC_BY_KEY:
        return _TOPIC_BY_KEY[key]
    sub_key = topic_key(subtopic)
    if sub_key in SUBTOPIC_TOPIC:
        return SUBTOPIC_TOPIC[sub_key]
    if learned and sub_key in learned:
        return learned[sub_key]
    return TOPIC_ALIASES.get(key)


# --- текст обращения --------------------------------------------------------

_SUBTOPIC_PREFIX = re.compile(r"^\s*Подтема запроса:\s*(.*?)\s*/\s*(.*)$", re.DOTALL)
# Разметка тикет-системы: <c #1a1a1a>, <m #ffff00>, <p>, <td rowspan="6">
_MARKUP = re.compile(
    r"</?(?:c|m)(?:\s+#[0-9a-f]{3,8})?\s*>"
    r"|</?(?:td|tr|th|table|tbody|thead|br|p|li|ul|ol|h[1-6]|div|span|center|b|i|u|strong|em)(?:\s+[^<>]*)?/?>",
    re.IGNORECASE,
)
# Отчёт об ошибке, который портал сам кладёт в обращение. После «Решение:» идёт
# подсказка портала — то есть почти ответ; модели темы её видеть нельзя, иначе
# она учится на подсказке, а не на словах человека.
_ERROR_REPORT = re.compile(
    r"(?:I?D\s+запроса\s+поддержки:\s*\w*\s*,?\s*)?Текст\s+ошибки:\s*(?P<error>.+?)\s*,\s*ID\s+шаблона:.*$",
    re.IGNORECASE | re.DOTALL,
)
_SIGNATURE = re.compile(r"\s(?:с уважением|заранее спасибо|спасибо заранее)\b.*$", re.IGNORECASE | re.DOTALL)
_SPACES = re.compile(r"\s+")
#: Дальше первых полутора тысяч символов тему не уточнить, а эмбеддер и так режет по 512 токенам
MAX_TEXT_CHARS: Final = 1500


def appeal_text(description: str) -> tuple[str, str]:
    """«Подтема запроса: X/текст» → (подтема, текст обращения без разметки и хвоста).

    Подтему из текста убираем: её выбирает сам заявитель из того же справочника,
    и модель, увидев её, выучила бы копирование подписи, а не понимание вопроса —
    в чате подтемы нет. Хвост — отчёт портала после «Решение:» и подпись.
    """
    matched = _SUBTOPIC_PREFIX.match(description or "")
    subtopic, text = (matched.group(1), matched.group(2)) if matched else ("", description or "")
    text = _SPACES.sub(" ", html.unescape(_MARKUP.sub(" ", text))).strip()
    report = _ERROR_REPORT.search(text)
    if report is not None:
        text = f"{text[: report.start()].strip(' ,.;')} Ошибка {report.group('error').strip()}".strip()
    text = _SIGNATURE.sub("", text).strip()
    return _SPACES.sub(" ", subtopic).strip(), text[:MAX_TEXT_CHARS]


_REQUEST_IMPACT = ("rfi", "rfc")


def is_incident(impact: str) -> bool:
    """Колонка «Влияние»: «RFI» и «RFC» — запросы, остальное — «услуга недоступна»."""
    head = (impact or "").strip().casefold()
    return bool(head) and not head.startswith(_REQUEST_IMPACT)


# --- правила регламента -----------------------------------------------------

#: Ключ адресата «одна из наших линий»; остальные ключи — внешние адресаты
LINE: Final = "line"
SKK: Final = "skk"
ARBITRATION: Final = "arbitration"
EAIST: Final = "eaist"

_ACCOUNT = r"(?:кабинет\w*|лк|профил\w*|организаци\w*|компани\w*|аккаунт\w*|учетн\w*\s+запис\w*|поставщик\w*)"
_BLOCK_VERB = r"(?:за|раз)?блокир\w*"
# Существительное «блокировка» в обращениях поставщика — почти всегда о кабинете:
# «срок блокировки истёк». Глагол — нет: «поле заблокировано», «ошибка не
# блокирует отправку». Поэтому глагол засчитываем только рядом с кабинетом.
# «Профиль зарегистрирован, ограничений нет» — не блокировка: отрицание рядом снимает совпадение
# Квантификатор «жадный без отката» (\w*+): иначе «ограничений нет» совпадало бы как
# «ограничени» + «й нет», и отрицание проскакивало мимо проверки.
_LIMITED = r"(?:(?<!нет )(?<!без )ограничени\w*+(?!\W+нет\b)|статус\w*\W+заблокирован\w*)"
_BLOCKED = re.compile(
    rf"блокировк\w*|разблокир\w*|\bрнп\b|реестр\w*\s+недобросовестн\w*"
    rf"|\b(?:нас|меня)\s+{_BLOCK_VERB}|{_BLOCK_VERB}\s+(?:нас|меня)\b"
    rf"|{_BLOCK_VERB}(?:\W+\w+){{0,3}}?\W+{_ACCOUNT}|{_ACCOUNT}(?:\W+\w+){{0,3}}?\W+{_BLOCK_VERB}"
    rf"|{_LIMITED}(?:\W+\w+){{0,2}}?\W+{_ACCOUNT}|{_ACCOUNT}(?:\W+\w+){{0,2}}?\W+{_LIMITED}",
)
# «Апелляция в арбитражный суд» — это суд, а не комиссия портала: такого
# человека ведёт СКК, а не форма жалобы в личном кабинете.
_APPEAL = re.compile(r"обжал\w*|жалоб\w*|оспор\w*")
_ARBITRATION = re.compile(r"арбитражн\w*\s+комисси\w*")
# Просьба снять КС с публикации, а не рассказ о снятой: «снята с публикации,
# в чём причина» и «причина снятия КС» — вопрос о причине, его решает линия
# закупок. Поэтому родительный падеж («снятия») в правило не входит.
_WITHDRAW = re.compile(
    r"(?<!причин[аыу] )(?:сн(?:ять|имите|имем|ятие|ятии)|отмен(?:ить|ите))\s+(?:\S+\s+){0,5}?с\s+публикаци\w*"
    r"|сн(?:ять|имите|ятие|ятии)\s+(?:котировочн\w*\s+сесси\w*|кс)\b"
)
_REGIONAL_CUSTOMER = re.compile(r"регион\w*|уполномоченн\w*\s+орган\w*|\bуо\b")
_SUPPLIER_SELF = re.compile(r"\bмы\s+поставщик\w*|\bя\s+поставщик\w*|\bкак\s+поставщик\w*")
# Явный сбой, а не вопрос «как»: у инцидентов выгрузки («услуга недоступна») это
# «не работает», «не открывается», «ошибка 500», «белый экран».
_OUTAGE = re.compile(
    r"не\s+(?:работает|работают|открывается|открываются|загружается|грузится)\s+(?:портал|сайт|систем\w*|"
    r"личн\w+\s+кабинет|лк|страниц\w*)|(?:портал|сайт|систем\w*|сервис\w*)\s+(?:не\s+работает|недоступ\w*)"
    r"|сбо[йяею]\w*|ошибк\w*\s+50[0234]|\b50[234]\b|бел\w+\s+экран|услуг\w*\s+недоступн\w*"
)


def _plain(text: str) -> str:
    return _SPACES.sub(" ", text.casefold().replace("ё", "е"))


def addressee_by_rules(text: str, audience: str = "") -> tuple[str, str]:
    """(адресат, правило) по словам обращения и роли собеседника; ("", "") — правила молчат.

    Правила — прямые положения регламента, а не догадка модели: обжалование
    блокировки рассматривает только Арбитражная комиссия, блокировку — СКК, а
    просьбу снять КС с публикации — тот, кого называет п. 5.1 правил КС.
    """
    plain = _plain(text)
    blocked = bool(_BLOCKED.search(plain))
    if _ARBITRATION.search(plain) or (blocked and _APPEAL.search(plain)):
        return ARBITRATION, "appeal_blocking"
    if blocked:
        return SKK, "blocking"
    if _WITHDRAW.search(plain):
        # Поставщик просит снять КС с неверными сведениями — через СКК (п. 5.4),
        # региональный заказчик — через СТП, заказчик Москвы — через СТП ЕАИСТ.
        if audience == "supplier" or _SUPPLIER_SELF.search(plain):
            return SKK, "withdraw_by_supplier"
        if _REGIONAL_CUSTOMER.search(plain):
            return LINE, "withdraw_regional"
        return EAIST, "withdraw_moscow"
    return "", ""


# Не работает инструмент подписи: «не работает ЭЦП при подписании», «не видит
# сертификат», «ошибка КриптоПро». Модель темы видела в таком «подписание» и
# отдавала его линии закупок и контрактов, хотя чинить надо подпись, а не
# контракт. Голое «подписание» сюда не входит: «ошибка при подписании контракта»
# чаще вопрос по контракту, и его решает модель темы.
_SIGNATURE_TOOL = (
    r"(?:эцп|\bэп\b|\bкэп\b|укэп|электронн\w*\s+подпис\w*"
    r"|сертификат\w*|криптопро|крипто\s+про|плагин\w*|токен\w*)"
)
_FAILS = (
    r"(?:не\s+(?:работает|работают|видит|видно|подключа\w*|устанавлива\w*|найден\w*|проходит|читается)"
    r"|ошибк\w*|не\s+удает\w*|не\s+получает\w*)"
)
_SIGNATURE_FAILURE = re.compile(
    rf"{_SIGNATURE_TOOL}(?:\W+\w+){{0,4}}?\W+{_FAILS}|{_FAILS}(?:\W+\w+){{0,4}}?\W+{_SIGNATURE_TOOL}"
)


def looks_like_outage(text: str) -> bool:
    """Сообщение о сбое («портал не работает», «ошибка 500») или о неработающей
    подписи («не работает ЭЦП», «не видит сертификат») — это техническая линия."""
    plain = _plain(text)
    return bool(_OUTAGE.search(plain) or _SIGNATURE_FAILURE.search(plain))


