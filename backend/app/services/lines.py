_NOT_WORD = re.compile(r"[^0-9a-zа-я]+")


def topic_key(text: str) -> str:
    """Ключ сравнения: регистр, «ё», скобки, дефисы и точки на конце роли не играют."""
    return _NOT_WORD.sub(" ", text.casefold().replace("ё", "е")).strip()


_TOPIC_BY_KEY: Final = {topic_key(topic): topic for topic in TOPICS}


def _unique_subtopics() -> dict[str, str]:
    """Подтема → тема, только если подтема встречается в справочнике один раз.

    «Консультация» есть у пяти тем — по ней тему не угадать, и такая запись
    честнее отбрасывается, чем приписывается первой попавшейся теме.
    """
    owners: dict[str, set[str]] = {}
    for topic, subtopics in SUBTOPICS.items():
        for subtopic in subtopics:
            owners.setdefault(topic_key(subtopic), set()).add(topic)
    return {key: next(iter(topics)) for key, topics in owners.items() if len(topics) == 1}


