"""Словоформы для текста, который читает человек: основа слова, служебные слова,
частые значимые слова.

Токены поиска (retrieval.tokenize) режут слово до шести букв. Для лексического
индекса это дёшево и достаточно, но в отчёте «операт» и «подпис» читаются как
опечатки, а пятибуквенные формы («линии», «линию») таким префиксом не склеиваются
вовсе. Поэтому формы одного слова группируем по основе — срезом окончаний, — а
показываем целое слово в той форме, в какой его чаще писали.
"""

import re
from collections import Counter
from collections.abc import Iterable

import snowballstemmer

_WORD = re.compile(r"[а-яёa-z0-9]+")
# Короче трёх букв — предлоги, союзы и частицы («не», «на», «ну»): смысла в них нет
_MIN_WORD_LEN = 3

# Служебные и пустые для темы жалобы слова. Сравниваются целиком (не по основе):
# основа «тем» у местоимения та же, что у «темы», а «темы» выбрасывать нельзя.
# Буква «ё» здесь записана как «е» — так же нормализуется и проверяемое слово.
STOPWORDS = frozenset(
    (
        # местоимения
        "меня мне мной нас нам нами вас вам вами тебя тебе тобой него нему ним нем нее ней "
        "его ему она они оно них ними себя себе собой сам сама само сами самим самих самой самого "
        "мой моя мое мои моего моей моему моим моих моими твой твоя твое твои "
        "наш наша наше наши нашего нашей нашим наших ваш ваша ваше ваши вашего вашей вашим ваших "
        "свой своя свое свои своего своей своим своих своими "
        "этот эта это эти этого этой этому этим этих тот того той тому тем том тех теми "
        "весь вся все всего всей всему всем всеми всех "
        "кто кого кому кем что чего чему чем какой какая какое какие какого каким каких "
        "который которая которое которые которого которой которым которых чей чья чье чьи "
        "никто ничто ничего ничем ничему никого никому нечего некого "
        # предлоги
        "для при про без над под перед через после около между кроме вместо ради среди возле "
        "мимо вокруг против насчет "
        # союзы, частицы, наречия меры и времени
        "или либо чтобы как так также тоже если хотя пока когда потому поэтому зато однако "
        "причем ведь вот даже лишь только уже еще вообще разве именно просто почти очень совсем "
        "слишком вовсе чуть едва вроде будто словно опять снова сразу всегда никогда иногда "
        "тогда потом теперь сейчас где куда откуда здесь тут там туда сюда нет ага ладно "
        # связки и модальные глаголы
        "был была было были быть будет будут буду будем есть стал стала стало стали "
        "можно нужно надо нельзя могу может могут мог могла хочу хотел хотела пришлось приходится "
        # вежливые формулы — те же, что отсекает поиск
        "здравствуйте привет добрый пожалуйста подскажите скажите спасибо заранее прошу просьба "
        "уважаемые "
        # числительные словами: число само по себе не тема жалобы
        "один одна одно одни два две три четыре пять шесть семь восемь девять десять раз раза"
    ).split()
)

# Основу считает эталонный русский Snowball (snowballstem.org/algorithms/russian):
# пакет сгенерирован из исходников самого алгоритма и словарей не требует
_RUSSIAN = snowballstemmer.stemmer("russian")


def stem(word: str) -> str:
    """Основа русского слова: формы одного слова дают одну основу.

    «оператор», «оператора», «операторов» → «оператор»; «линии», «линию» → «лин».
    Это не лемматизация — «ошибок» и «ошибка» расходятся, — зато без словарей,
    а для группировки ключевых слов этого хватает.
    """
    # «ё» пишут не всегда, а основа от этого зависеть не должна. Пакет без
    # аннотаций, поэтому ответ приводим к str явно
    return str(_RUSSIAN.stemWord(word.lower().replace("ё", "е")))


# 11–14 требуют «много», хотя кончаются на 1–4: «одиннадцать обращений»
_TEENS = range(11, 15)
_FEW = range(2, 5)


def plural(count: int, forms: tuple[str, str, str]) -> str:
    """Форма слова, согласованная с числом: forms — для 1, для 2–4 и для 5+.

    plural(21, ("обращение", "обращения", "обращений")) → «обращение».
    """
    tail = abs(count) % 100
    if tail in _TEENS:
        return forms[2]
    if tail % 10 == 1:
        return forms[0]
    if tail % 10 in _FEW:
        return forms[1]
    return forms[2]


def top_words(texts: Iterable[str], limit: int) -> list[str]:
    """Самые частые значимые слова текстов — целыми словами, как их писали.

    Формы одного слова считаются вместе (по основе), а показывается самая частая
    из них: «оператора» ×2 и «оператор» ×1 дают одно слово «оператора» с весом 3.
    При равных частотах раньше идёт то, что раньше встретилось, — список стабилен.
    """
    counts: Counter[str] = Counter()
    forms: dict[str, Counter[str]] = {}
    for text in texts:
        for word in _WORD.findall(text.lower()):
            if len(word) < _MIN_WORD_LEN or word.replace("ё", "е") in STOPWORDS:
                continue
            base = stem(word)
            counts[base] += 1
            forms.setdefault(base, Counter())[word] += 1
    return [forms[base].most_common(1)[0][0] for base, _ in counts.most_common(limit)]
