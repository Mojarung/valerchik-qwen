SECRET_KEYS = {"llm.api_key"}


class SettingsValueError(ValueError):
    """Значение настройки не подходит по типу или диапазону."""


class _Rejected(Exception):
    """Правка не подходит; текст — объяснение для администратора."""


def _whole(value: Any) -> int:
    if (
        isinstance(value, bool)
        or not isinstance(value, (int, float))
        or not math.isfinite(value)
        or value < 0
        or value != int(value)
    ):
        raise _Rejected("ожидается неотрицательное целое число")
    return int(value)


def _number(value: Any) -> float:
    if (
        isinstance(value, bool)
        or not isinstance(value, (int, float))
        or not math.isfinite(value)
        or value < 0
    ):
        raise _Rejected("ожидается неотрицательное число")
    return float(value)


def _exactly(kind: type, message: str) -> Callable[[Any], Any]:
    def check(value: Any) -> Any:
        if not isinstance(value, kind):
            raise _Rejected(message)
        return value

    return check


# Порядок важен: bool — подкласс int, и без первой строки проверка «целое»
# пропускала True в числовую настройку.
_CHECKS: tuple[tuple[type, Callable[[Any], Any]], ...] = (
    (bool, _exactly(bool, "ожидается да/нет")),
    (int, _whole),
    (float, _number),
    (list, _exactly(list, "ожидается список значений")),
    (dict, _exactly(dict, "ожидается объект")),
    (str, _exactly(str, "ожидается строка")),
)


def _coerce(default: Any, value: Any) -> Any:
    """Привести правку к типу значения по умолчанию или объяснить, почему нельзя."""
    for kind, check in _CHECKS:
        if isinstance(default, kind):
            return check(value)
    return value


_AUTO_RANGES = {
    "source_conflicts.auto_debounce_seconds": (0, 300),
    "source_conflicts.auto_max_neighbours": (1, 20),
    "source_conflicts.auto_daily_call_limit": (0, 50000),
    "source_conflicts.auto_max_attempts": (1, 1),
    "source_conflicts.auto_retry_seconds": (1, 3600),
}


def validate_updates(updates: dict[str, Any]) -> dict[str, Any]:
    """Проверить правки до записи и вернуть приведённые значения.

    Тип берём у значения по умолчанию: настройки типизированы им и ничем больше.
    Без проверки строка в `agent.timeout_s` доезжала до обработки сообщения и
    падала там пятисоткой у пользователя — то есть ошибка администратора
    превращалась в поломку чата спустя произвольное время.
    """
    cleaned: dict[str, Any] = {}
    problems: list[str] = []
    for key, value in updates.items():
        spec = SETTINGS.get(key)
        if spec is None:
            problems.append(f"{key}: неизвестная настройка")
            continue
        try:
            cleaned[key] = _coerce(spec.default, value)
            if key in _AUTO_RANGES:
                minimum, maximum = _AUTO_RANGES[key]
                if not minimum <= cleaned[key] <= maximum:
                    raise _Rejected(f"ожидается значение от {minimum} до {maximum}")
        except _Rejected as rejected:
            problems.append(f"{key}: {rejected}")
    if problems:
        raise SettingsValueError("; ".join(problems))
    return cleaned


class DynamicSettings:
    """get() — мгновенный доступ из памяти; set() — БД + broadcast всем инстансам."""

    def __init__(
        self, session_factory: SessionFactory, cache: Redis, env_overrides: dict[str, Any] | None = None
    ) -> None:
        self._session_factory = session_factory
        self._cache = cache
        # значения из ENV применяются как дефолты ПЕРВОГО запуска (пока ключа нет в БД);
        # дальше источник истины — БД + админка. Пустые строки игнорируем, False — валидное значение
        self._env_overrides = {k: v for k, v in (env_overrides or {}).items() if v not in ("", None)}
        self._values: dict[str, Any] = {key: spec.default for key, spec in SETTINGS.items()}
        self._listener_task: asyncio.Task[None] | None = None

    def get(self, key: str, default: Any = None) -> Any:
        if default is None and key in SETTINGS:
            default = SETTINGS[key].default
        return self._values.get(key, default)

    def override(self, key: str, value: Any) -> None:
        """Значение только для этого процесса (замеры, утилиты): в БД и другим инстансам не уходит."""
        self._values[key] = value

    def all(self, mask_secrets: bool = True) -> list[dict[str, Any]]:
        out = []
        for key, spec in SETTINGS.items():
            value = self._values.get(key, spec.default)
            secret = key in SECRET_KEYS
            if mask_secrets and secret and value:
                # Полностью, без первых символов: по префиксу ключа опознаётся и
                # провайдер, и окружение, ради которого ключ вообще прячут.
                value = "***"
            out.append(
                {
                    "key": key,
                    "value": value,
                    "category": spec.category,
                    "label": spec.label,
                    "description": spec.description,
                    "secret": secret,
                }
            )
        return out

    async def load(self) -> None:
        """Читает БД, добивает отсутствующие ключи дефолтами."""
        async with self._session_factory() as session:
            rows = (await session.execute(select(SettingEntry))).scalars().all()
            existing = {r.key: r for r in rows}
            for key, spec in SETTINGS.items():
                if key in existing:
                    self._values[key] = existing[key].value.get("v", spec.default)
                else:
                    value = self._env_overrides.get(key, spec.default)
                    session.add(
                        SettingEntry(
                            key=key, value={"v": value}, category=spec.category, description=spec.description
                        )
                    )
                    self._values[key] = value
            await session.commit()

    async def set_many(self, updates: dict[str, Any], actor: str = "admin") -> list[str]:
        updates = validate_updates(updates)
        changed: list[str] = []
        async with self._session_factory() as session:
            for key, value in updates.items():
                if key not in SETTINGS:
                    continue
                row = await session.get(SettingEntry, key)
                if row is None:
                    spec = SETTINGS[key]
                    row = SettingEntry(key=key, category=spec.category, description=spec.description)
                    session.add(row)
                row.value = {"v": value}
                self._values[key] = value
                changed.append(key)
            await session.commit()
        if changed:
            await self._cache.publish(CHANNEL, json.dumps({"keys": changed, "actor": actor}))
        return changed

    async def start_listener(self) -> None:
        """Подписка на изменения от других инстансов — hot-reload без рестарта."""
        pubsub = self._cache.pubsub()
        await pubsub.subscribe(CHANNEL)

        async def _listen() -> None:
            async for message in pubsub.listen():
                if message.get("type") != "message":
                    continue
                try:
                    await self.load()
                    log.info("Настройки перечитаны: %s", message.get("data"))
                except Exception:
                    log.exception("Ошибка перечитывания настроек")

        self._listener_task = asyncio.create_task(_listen())

    async def stop(self) -> None:
        if self._listener_task:
            self._listener_task.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await self._listener_task
