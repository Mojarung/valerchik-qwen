"""Модели ответов роутера auth."""

from app.schemas.base import ApiModel


class MeResponse(ApiModel):
    """Кто сейчас за клавиатурой.

    Фронт зовёт эту ручку на старте вместо чтения токена: сам токен лежит в
    httpOnly-куке и из JS не читается. Аноним получает 200 с пустой ролью, а не
    401: «сессии нет» — это нормальный ответ о состоянии, а не ошибка, и на
    публичной странице чата 401 каждому посетителю сорил бы в консоль браузера
    и в счётчики ошибок.
    """

    user_id: str | None = None
    username: str | None = None
    role: str | None = None
    display_name: str | None = None
    # Линия поддержки оператора: её очередь он и видит. У админа и у оператора
    # без линии — None.
    line: int | None = None
