import { describe, expect, it } from "vitest";
import { plural } from "./plural";

const APPEALS = ["обращение", "обращения", "обращений"] as const;

describe("plural", () => {
  // Карточка кластера писала «1 обращений» и «3 обращений»: форма была одна на все числа
  it.each([
    [1, "обращение"],
    [21, "обращение"],
    [101, "обращение"],
    [2, "обращения"],
    [4, "обращения"],
    [22, "обращения"],
    [5, "обращений"],
    [0, "обращений"],
    [11, "обращений"],
    [12, "обращений"],
    [14, "обращений"],
    [111, "обращений"],
    // дробь — как 2–4: «1,5 обращения»
    [1.5, "обращения"],
  ])("%s → %s", (count, form) => {
    expect(plural(count, APPEALS)).toBe(form);
  });
});
