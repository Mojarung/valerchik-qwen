#!/usr/bin/env bash
# Резервная копия стенда: база + файлы (иллюстрации методичек, вложения операторов).
#
# Что НЕ копируем осознанно:
#   - том Qdrant: это производный индекс, он пересобирается из той же базы
#     кнопкой «Переиндексировать» в админке. Копия удвоила бы вес архива без пользы.
#   - кеш моделей TEI и docling: качается из интернета.
#
# Это копия «по требованию». По расписанию их снимает контейнер backup, а как
# часто и сколько хранить — настраивается в админке (раздел «Резервные копии»).
#
# Использование:
#   ./scripts/backup.sh                 -> backups/manual-<дата>/
#   BACKUP_DIR=/mnt/disk ./scripts/backup.sh
set -euo pipefail

cd "$(dirname "$0")/.."

BACKUP_DIR="${BACKUP_DIR:-backups}"
STAMP="$(date +%Y%m%d-%H%M%S)"
# manual-, а не auto-: ротация в контейнере backup чистит только автокопии,
# и снятое человеком руками переживает любую настройку «хранить N копий».
OUT="$BACKUP_DIR/manual-$STAMP"
mkdir -p "$OUT"

# Формат custom (-Fc), а не обычный SQL: сжат, восстанавливается pg_restore
# выборочно и параллельно, и не ломается о порядок внешних ключей.
echo "→ база данных…"
docker compose exec -T postgres pg_dump -U support -d support -Fc > "$OUT/support.dump"

# Картинки лежат в томе, а не в БД: без них статьи останутся со ссылками в никуда.
# Команда завёрнута в sh -c намеренно: в Git Bash на Windows аргумент «/data»
# подменяется на «C:/Program Files/Git/data» ещё до запуска docker, и tar падает.
# Внутри строки для sh -c такой подмены не происходит.
echo "→ файлы (иллюстрации и вложения)…"
docker compose exec -T api sh -c 'tar -cz -C /data media' > "$OUT/media.tar.gz"

# Настройки, ключи и режим стенда — восстанавливать стек без них бессмысленно.
# .env в копию не кладём: ключ LLM и пароль базы размножались бы по каталогу
# копий, смонтированному в контейнер на запись. Секреты восстанавливают из
# менеджера секретов, а не из бэкапа — об этом сказано в README.
[ -f .env ] && grep -oE '^[A-Z_]+' .env | sed 's/$/=/' > "$OUT/env.keys"

cat > "$OUT/manifest.txt" <<EOF
Валерчик — резервная копия
создана:        $(date --iso-8601=seconds)
база:           support.dump (pg_dump -Fc)
файлы:          media.tar.gz (/data/media)
окружение:      env.keys (имена переменных без значений)
восстановление: ./scripts/restore.sh $OUT
EOF

du -sh "$OUT"/* | sed 's/^/  /'
echo "✔ готово: $OUT"
